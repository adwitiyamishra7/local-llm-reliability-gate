"""Train + calibrate the deployable V5 gate.

Threshold comes ONLY from selected_threshold_v5.json (written by
risk_coverage_analysis.py from train-only OOF predictions). Nothing here looks at
test performance. V4 artifacts are never touched.

    python scripts\\finalize_gate_v5.py

Requires:
    artifacts/results/benchmark_results_v5_labeled.csv (V5 data with reference-audited labels)
    artifacts/classifier/selected_threshold_v5.json  (generated by risk_coverage_analysis.py --tag v5)
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import joblib
import pandas as pd
from sklearn.calibration import CalibratedClassifierCV
from sklearn.ensemble import ExtraTreesClassifier

ROOT_DIR = Path(__file__).resolve().parents[1]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.gate.config import (
    CLASSIFIER_DIR, EXPECTED_FEATURES, GATE_FILE_V5, PROMPT_VERSION,
    config_fingerprint, generation_config,
)
from scripts.benchmark_300_v4 import label_correct
from scripts.benchmark_provenance import audit_reference_provenance

TARGET = "consensus_correct"
MIN_OOF_SEEDS_MEETING_TARGET = 1
EXPECTED_BENCHMARK_ROWS = 300
MINIMUM_CLASS_ROWS = 25


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default="benchmark_results_v5_labeled.csv")
    ap.add_argument("--threshold-json", default="selected_threshold_v5.json")
    args = ap.parse_args()

    input_file = ROOT_DIR / "artifacts" / "results" / args.input
    thr_file = CLASSIFIER_DIR / args.threshold_json

    for f in (input_file, thr_file):
        if not f.exists():
            raise FileNotFoundError(
                f"Missing {f}.\n"
                "Run the V5 benchmark, reference-label audit, and risk-coverage analysis first:\n"
                "  python scripts\\benchmark_300_v4.py --output benchmark_results_v5.csv\n"
                "  python scripts\\relabel_v5_benchmark.py\n"
                "  python scripts\\risk_coverage_analysis.py "
                "--input benchmark_results_v5_labeled.csv --tag v5"
            )

    df = pd.read_csv(input_file)
    source_rows = len(df)

    fingerprint = config_fingerprint()
    if "generation_fingerprint" not in df.columns:
        raise SystemExit(
            "benchmark CSV is missing the generation_fingerprint column. "
            "Regenerate it using benchmark_300_v4.py."
        )
    saved_fps = set(df["generation_fingerprint"].unique())
    if saved_fps != {fingerprint}:
        raise SystemExit(
            f"Benchmark was generated with fingerprint(s) {saved_fps!r}, "
            f"but the current V5 config fingerprint is {fingerprint!r}. "
            "Regenerate with benchmark_300_v4.py under the current configuration."
        )

    required_provenance = {
        "row_id", "question", "reference", "consensus_answer",
        "question_id", "prompt_version", "label_method", "reference_dataset_sha256",
    }
    missing_provenance = sorted(required_provenance - set(df.columns))
    if missing_provenance:
        raise SystemExit(f"Benchmark is missing provenance columns: {missing_provenance}")
    row_ids = pd.to_numeric(df["row_id"], errors="coerce")
    expected_ids = set(range(EXPECTED_BENCHMARK_ROWS))
    if (
        len(df) != EXPECTED_BENCHMARK_ROWS
        or row_ids.isna().any()
        or row_ids.duplicated().any()
        or set(row_ids.astype(int)) != expected_ids
    ):
        raise SystemExit(
            f"Refusing to train on an incomplete or duplicated benchmark: "
            f"rows={len(df)}, unique_ids={row_ids.nunique(dropna=True)}; "
            f"expected exactly IDs 0..{EXPECTED_BENCHMARK_ROWS - 1}."
        )
    if set(df["prompt_version"].astype(str)) != {PROMPT_VERSION}:
        raise SystemExit("Benchmark prompt_version values do not match the current V5 prompt.")
    if set(df["label_method"].astype(str)) != {"reference_alias_exact_v2"}:
        raise SystemExit("Benchmark labels have not been audited against the stored references.")
    source_hash, provenance_errors = audit_reference_provenance(df)
    if provenance_errors or set(df["reference_dataset_sha256"].astype(str)) != {source_hash}:
        raise SystemExit(
            "Benchmark question/reference provenance does not match the canonical source: "
            + "; ".join(provenance_errors[:5])
        )
    if df[["question", "reference", "consensus_answer"]].isna().any().any():
        raise SystemExit("Benchmark contains missing questions, references, or generated answers.")
    if df[["question", "reference"]].astype(str).apply(lambda c: c.str.strip().eq("")).any().any():
        raise SystemExit("Benchmark contains blank questions or reference answers.")

    missing = [c for c in EXPECTED_FEATURES + [TARGET] if c not in df.columns]
    if missing:
        raise SystemExit(f"Missing columns: {missing}")

    values = df[EXPECTED_FEATURES].apply(pd.to_numeric, errors="coerce")
    labels = pd.to_numeric(df[TARGET], errors="coerce")
    if values.isna().any().any() or not values.map(math.isfinite).all().all():
        raise SystemExit("Benchmark features contain missing or non-finite values.")
    if labels.isna().any() or not set(labels.unique()).issubset({0, 1}):
        raise SystemExit("Benchmark labels must be present and binary (0/1).")
    reproduced = [
        label_correct(answer, reference)
        for answer, reference in zip(df["consensus_answer"], df["reference"])
    ]
    if reproduced != labels.astype(int).tolist():
        raise SystemExit("Benchmark labels do not reproduce from the stored reference answers.")
    question_keys = (
        df["question"].astype(str).str.casefold()
        .str.replace(r"\s+", " ", regex=True).str.strip()
    )
    duplicate_questions = int(question_keys.duplicated().sum())
    if duplicate_questions:
        df = df.loc[~question_keys.duplicated(keep="first")].copy()
        values = values.loc[df.index]
        labels = labels.loc[df.index]
    thr_data = json.loads(thr_file.read_text(encoding="utf-8"))
    threshold = float(thr_data["threshold"])
    if not 0.0 <= threshold <= 1.0:
        raise SystemExit(f"Selected threshold is outside [0,1]: {threshold}")
    if (
        thr_data.get("input_file") != input_file.name
        or thr_data.get("rows") != len(df)
        or thr_data.get("source_rows") != source_rows
        or thr_data.get("unique_question_rows") != len(df)
        or thr_data.get("duplicate_questions_excluded") != duplicate_questions
        or thr_data.get("generation_fingerprint") != fingerprint
        or thr_data.get("reference_dataset_sha256") != source_hash
        or thr_data.get("prompt_version") != PROMPT_VERSION
    ):
        raise SystemExit("Selected threshold metadata does not match this complete V5 benchmark.")
    if thr_data.get("seeds") != [42]:
        raise SystemExit("V5 deployment requires the pre-registered independent holdout split (seed 42).")
    all_question_ids = set(df["question_id"].astype(str))
    training_question_ids = set(map(str, thr_data.get("training_question_ids", [])))
    heldout_question_ids = set(map(str, thr_data.get("heldout_question_ids", [])))
    if (
        not training_question_ids
        or not heldout_question_ids
        or training_question_ids & heldout_question_ids
        or (training_question_ids | heldout_question_ids) != all_question_ids
    ):
        raise SystemExit(
            "Training and held-out question IDs must form a non-empty, disjoint partition "
            "of all unique audited questions."
        )
    train_mask = df["question_id"].astype(str).isin(training_question_ids)
    df_train = df.loc[train_mask].copy()
    values_train = values.loc[df_train.index]
    labels_train = labels.loc[df_train.index]
    X = values_train.astype(float)
    y = labels_train.astype(int)

    class_counts = y.value_counts()
    if len(class_counts) != 2 or int(class_counts.min()) < MINIMUM_CLASS_ROWS:
        raise SystemExit(
            f"Training split has insufficient class support for 5-fold calibration: "
            f"{class_counts.to_dict()}; need at least {MINIMUM_CLASS_ROWS} examples "
            "of each label. No artifact was written."
        )

    if len(training_question_ids) != thr_data.get("training_rows"):
        raise SystemExit("Threshold metadata training-row count does not match its training question IDs.")
    if len(heldout_question_ids) != thr_data.get("heldout_rows"):
        raise SystemExit("Threshold metadata held-out row count does not match its question IDs.")

    print(
        f"Training rows: {len(df_train)} unique questions; held out: {len(heldout_question_ids)}; "
        f"source rows: {source_rows}; duplicates excluded: {duplicate_questions}; "
        f"train correct={int(y.sum())} wrong={int((1 - y).sum())}"
    )
    heldout_accuracy = float(thr_data.get("heldout_mean_trusted_accuracy", float("nan")))
    heldout_trusted_count = float(thr_data.get("heldout_mean_trusted_count", 0.0))
    heldout_min_accuracy = float(thr_data.get("heldout_min_trusted_accuracy", float("nan")))
    heldout_min_count = int(thr_data.get("heldout_min_trusted_count", 0))
    heldout_target = float(thr_data.get("min_trusted_accuracy_target", 0.90))
    if (
        not math.isfinite(heldout_accuracy)
        or heldout_trusted_count <= 0
        or heldout_accuracy < heldout_target
        or not math.isfinite(heldout_min_accuracy)
        or heldout_min_accuracy < heldout_target
        or heldout_min_count <= 0
        or thr_data.get("heldout_all_seeds_meet_target") is not True
    ):
        raise SystemExit(
            f"Held-out evaluation did not validate the selected operating point: "
            f"trusted_accuracy={heldout_accuracy!r}, mean_trusted_count={heldout_trusted_count!r}, "
            f"minimum_seed_accuracy={heldout_min_accuracy!r}, min_seed_trusted_count={heldout_min_count}, "
            f"all_seeds_pass={thr_data.get('heldout_all_seeds_meet_target')!r}, "
            f"required_accuracy={heldout_target:.0%}. No artifact was written; keep TRUST disabled."
        )
    met = int(thr_data["seeds_meeting_oof_target"])
    n_seeds = len(thr_data["seeds"])

    if met < MIN_OOF_SEEDS_MEETING_TARGET:
        raise SystemExit(
            f"Only {met}/{n_seeds} seeds reached the "
            f"{thr_data['min_trusted_accuracy_target']:.0%} trusted-accuracy target "
            "on train-OOF predictions, so this threshold is not a validated "
            "operating point. No artifact was written; keep TRUST disabled."
        )

    print(
        f"Threshold: {threshold:.2f}  "
        f"(from {thr_data['selection_rule']}, "
        f"{met}/{n_seeds} seeds met target)"
    )

    base = ExtraTreesClassifier(
        n_estimators=500,
        max_depth=7,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )
    model = CalibratedClassifierCV(estimator=base, method="sigmoid", cv=5, n_jobs=-1)
    print("Training ExtraTreesClassifier + sigmoid calibration on training questions only...")
    model.fit(X, y)
    print("Training complete.")

    cfg = generation_config()
    payload = {
        "model": model,
        "feature_names": list(EXPECTED_FEATURES),
        "trust_threshold": threshold,
        "target_name": TARGET,
        "model_type": "ExtraTreesClassifier + Sigmoid Calibration",
        "dataset_rows": int(len(df_train)),
        "benchmark_source_rows": int(source_rows),
        "unique_question_rows": int(len(df)),
        "duplicate_questions_excluded": int(duplicate_questions),
        "heldout_question_rows": int(len(heldout_question_ids)),
        "training_question_ids": sorted(training_question_ids),
        "heldout_question_ids": sorted(heldout_question_ids),
        "label_method": "reference_alias_exact_v2",
        "reference_dataset_sha256": source_hash,
        "correct_rows": int(y.sum()),
        "wrong_rows": int((1 - y).sum()),
        "threshold_source": thr_data["selection_rule"],
        "threshold_details": thr_data,
        "benchmark_file": str(input_file),
        "version": f"final_v5_{PROMPT_VERSION}",
        "prompt_version": PROMPT_VERSION,
        "generation_config": cfg,
        "generation_fingerprint": fingerprint,
    }

    CLASSIFIER_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(payload, GATE_FILE_V5)

    # Reload check
    again = joblib.load(GATE_FILE_V5)
    p = again["model"].predict_proba(X.head(3))[:, 1]

    meta_text = f"""LOCAL LLM RELIABILITY GATE - FINAL MODEL (V5)

Prompt version: {PROMPT_VERSION}
Generation fingerprint: {fingerprint}
Model: {cfg['model_name']} | samples={cfg['n_samples']} | max_new_tokens={cfg['max_new_tokens']}
Sampling: temperature={cfg['temperature']} top_p={cfg['top_p']} top_k={cfg['top_k']}

Classifier: ExtraTreesClassifier + sigmoid calibration
Training rows: {len(df_train)}; held-out questions: {len(heldout_question_ids)}
Unique source questions: {len(df)} from {source_rows} benchmark rows
Duplicate questions excluded: {duplicate_questions}
Labels: reference_alias_exact_v2 (not model-agreement labels)
Reference dataset SHA-256: {source_hash}
Training classes: correct {int(y.sum())}, wrong {int((1 - y).sum())}
Benchmark file: {input_file.name}

Features ({len(EXPECTED_FEATURES)}):
{chr(10).join('- ' + f for f in EXPECTED_FEATURES)}

Deployment threshold: {threshold:.2f}
Source: {thr_data['selection_rule']}
Per-seed OOF thresholds: {thr_data['per_seed_thresholds']}
Seeds meeting OOF trusted-accuracy target: {met}/{n_seeds}
Held-out trusted accuracy at selected threshold: {heldout_accuracy:.2%}
Minimum per-seed held-out trusted accuracy: {heldout_min_accuracy:.2%}
Held-out mean coverage: {float(thr_data['heldout_mean_coverage']):.2%}

Decision: P(correct) >= {threshold:.2f} -> TRUST, otherwise VERIFY.
Threshold was chosen from train-OOF predictions only, never from test results.
This is a reliability/abstention gate, not a truth detector.

Independent verification rule: {cfg.get('independent_verification_rule', 'N/A')}
TRUST additionally requires an independent verifier result of VERIFIED.
"""
    (CLASSIFIER_DIR / "final_gate_metadata_v5.txt").write_text(meta_text, encoding="utf-8")

    print(f"\nSaved {GATE_FILE_V5}")
    print(f"Threshold {threshold:.2f} | prompt {PROMPT_VERSION} | fingerprint {fingerprint}")
    print(f"Reload check OK (sample P(correct): {[round(float(v), 3) for v in p]})")


if __name__ == "__main__":
    main()
